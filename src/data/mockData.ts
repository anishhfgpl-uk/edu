// Helper to generate attendance for current month (September 2026) and August 2026
export function generateInitialAttendance(studentId: string): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  
  // September 2026 (Days 1 to 18)
  for (let day = 1; day <= 18; day++) {
    const dayStr = day < 10 ? `0${day}` : `${day}`;
    const dateStr = `2026-09-${dayStr}`;
    const dayOfWeek = new Date(2026, 8, day).getDay(); // 0 is Sunday, 6 is Saturday

    if (dayOfWeek === 0) {
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'holiday',
        remarks: 'Sunday Weekend',
      });
    } else if (dayOfWeek === 6 && day === 12) {
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'holiday',
        remarks: '2nd Saturday School Off',
      });
    } else if (day === 5) {
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'holiday',
        remarks: 'Teachers Day Celebration / Half Day',
      });
    } else if (day === 9) {
      // 1 absent day
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'absent',
        remarks: 'Informed fever (Medical prescription submitted)',
      });
    } else if (day === 10) {
      // 1 approved leave
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'leave',
        remarks: 'Sick Leave approved by Class Teacher',
      });
    } else {
      // Present
      const minutes = Math.floor(Math.random() * 18) + 48; // 7:48 to 8:06 AM
      const timeStr = `08:${minutes < 60 ? (minutes < 10 ? '0' + minutes : minutes) : '05'} AM`;
      records.push({
        id: `att-sep-${day}`,
        studentId,
        date: dateStr,
        status: 'present',
        timeIn: timeStr,
        remarks: 'On Time & Smart Uniform',
      });
    }
  }

  // August 2026 (Complete Month 1 to 31)
  for (let day = 1; day <= 31; day++) {
    const dayStr = day < 10 ? `0${day}` : `${day}`;
    const dateStr = `2026-08-${dayStr}`;
    const dayOfWeek = new Date(2026, 7, day).getDay();

    if (dayOfWeek === 0) {
      records.push({
        id: `att-aug-${day}`,
        studentId,
        date: dateStr,
        status: 'holiday',
        remarks: 'Sunday',
      });
    } else if (day === 15) {
      records.push({
        id: `att-aug-${day}`,
        studentId,
        date: dateStr,
        status: 'holiday',
        remarks: 'Independence Day Celebrations',
      });
    } else if (day === 18) {
      records.push({
        id: `att-aug-${day}`,
        studentId,
        date: dateStr,
        status: 'leave',
        remarks: 'Family function leave approved',
      });
    } else {
      records.push({
        id: `att-aug-${day}`,
        studentId,
        date: dateStr,
        status: 'present',
        timeIn: '08:02 AM',
        remarks: 'Present',
      });
    }
  }

  return records;
}

